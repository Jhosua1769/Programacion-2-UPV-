function filtrar(lista, check) {

    let lista2 = [];

    let j = 0;

    for (let i = 0; i < lista.length; i++) {
       if (check(lista[i])) {
            lista2[j] = lista[i];
            j++;
       }
    }

    return lista2;
}
// ------------------------------------------------
// ------------------------------------------------
// n: R 
//
// ->
// check()
// -> 
//
// V/F
// ------------------------------------------------
// ------------------------------------------------


function check(n){
    if (n === 5) {
        return true
    }

    return false
}

//main

let lista = [5,5,4,3,5];

let lista2 = filtrar(lista, check);

for (let i = 0; i < lista2.length; i++) {
    if (lista2[i] != 5) {
        console.log("error");
    }
    
}


